#!/usr/bin/env python3
"""Сигнатура дизайн-одиниці — спільна для того, хто її ЗАПИСУЄ, і того, хто її
ЧИТАЄ.

Модуль існує рівно тому, що інакше регулярка жила б у двох файлах. `design-hash
.py` кладе сигнатуру в `index.yaml` як базову лінію, `design-emit.py` рахує
поточну і віднімає одну від одної. Розійдись ці два обчислення хоч на символ —
різниця перестала б означати «що змінилось» і почала б означати «чим ці два
файли не згодні». Тому обчислення одне, і воно тут.

Ім'я файла з підкресленням, а не з дефісом, — щоб його можна було
`import`увати: сусіди-скрипти лежать у тій самій теці, отже в `sys.path[0]`.

**Форма токена, а не «крапка між літерами» (C1 рев'ю 2026-08-21).** Регулярка
сама по собі ловить будь-який `слово.слово`: у живій базовій лінії через це
лежали `support.js`, `fonts.googleapis.com`, `this.props.ring`, `dc.html`,
`spec.md`. Ціна не косметична: емітер визнає причиною будь-який токен, що
з'явився в КОЖНІЙ зміненій одиниці, тож одне оновлення рантайму експортера
(`runtime.support-v2.js` у всіх шести файлах) знімало `unexplained` до нуля і
гасило єдину ескалацію петлі рядком, що до дизайну стосунку не має.

Тому кандидат мусить лежати у ВІДОМОМУ ПРОСТОРІ ІМЕН: перший сегмент —
з `TOKEN_ROOTS`, а цей перелік виведений із `tokens.json` кіта, джерела істини
для імен токенів (`roots_of_token_file` нижче — та сама функція, якою його
рахує пін на дрейф).

Чому простір імен, а не повне ім'я зі списку: НОВОГО токена в `tokens.json` ще
немає в ту мить, коли він з'явився в макеті, — а це рівно той випадок, заради
якого емітер існує. Перевірка по повному імені осліпила б його на головній
причині; перевірка по кореню лишає нові імена всередині відомої родини
видимими, а чужі родини (`support`, `fonts`, `this`, `runtime`) відкидає.
"""
import json
import re

# Токеноподібні рядки: hex-кольори і `token.path`. Це лише ФОРМА — простір імен
# перевіряється окремо, нижче.
TOKENISH = re.compile(r"#[0-9A-Fa-f]{6}\b|\b[a-z]+(?:\.[a-z-]+){1,3}\b")

# Корені простору імен, виведені з `tokens.json` кіта (верхні ключі + перший
# сегмент кожного складеного ключа). Перелік літеральний, бо сигнатуру рахують
# два процеси в різний час і читати чужий файл на кожен виклик означало б, що
# базова лінія залежить від стану сусіднього репозиторію. Від дрейфу його
# стереже пін: `roots_of_token_file(<живий tokens.json>) == TOKEN_ROOTS`.
TOKEN_ROOTS = frozenset({
    "bg", "border", "color", "elevation", "motion", "overlay",
    "primary", "radius", "spacing", "text", "typography", "vote",
})

_ROOT_RE = re.compile(r"[a-z]+\Z")


def roots_of_token_file(path):
    """Корені простору імен із `tokens.json` — джерела істини для імен токенів.

    Верхній ключ (`color`, `spacing`, `motion`) — корінь. Складений ключ
    (`bg.canvas`, `vote.yes-but`) віддає коренем свій перший сегмент. Проміжні
    прості ключі (`light`, `dark`, `styles`) коренями НЕ стають: `light.bg`
    ім'ям токена ніхто не пише.
    """
    doc = json.load(open(path, encoding="utf-8"))
    roots = set()

    def walk(node, depth):
        if not isinstance(node, dict):
            return
        for key, value in node.items():
            if depth == 0:
                roots.add(key)
            if "." in key:
                roots.add(key.split(".", 1)[0])
            walk(value, depth + 1)

    walk(doc, 0)
    # `_meta` та інші службові ключі формою токена не є — регулярка їх однаково
    # не зловить, і тримати їх у просторі імен означало б розширювати його
    # рядками, яких у сигнатурі не буває.
    return frozenset(r for r in roots if _ROOT_RE.match(r))


def is_token(s):
    """Кандидат має форму дизайн-токена: hex або шлях у відомому просторі імен."""
    if s.startswith("#"):
        return True
    return s.split(".", 1)[0] in TOKEN_ROOTS


def tokens_of(data):
    """Множина токеноподібних рядків одного файла (bytes → set[str])."""
    return {s for s in TOKENISH.findall(data.decode("utf-8", "replace"))
            if is_token(s)}


def dc_truncated(rel, data):
    """Доказ повноти `.dc.html`: файл мусить ЗАКІНЧУВАТИСЬ на `</html>`.

    Тут же, а не двома копіями в хешері й емітері, з тієї самої причини, що й
    сигнатура: два обчислення розійшлись би, і різниця почала б означати «чим
    ці два файли не згодні».

    Було `b"</html>" not in data[-4096:]` — вікно в 4 КіБ, і воно хибило в
    обидва боки (I5 рев'ю 2026-08-21):

    * канвас із прикладом HTML усередині містить `</html>` у ТІЛІ; файл
      обрізано по кепу читання — рядок є, у хвості його немає, але й вікно його
      не бачить лише поки обрубок довший за 4 КіБ. Проба `data[-4096:]` → `data`
      пережила весь набір: жоден випадок не мав `</html>` у тілі й не в кінці,
      тож перевірялась наявність рядка, а не те, що ним файл закінчується;
    * повний документ із хвостом понад 4 КіБ (порожні рядки, якими редактор
      добиває файл) давав rc=3 на цілому файлі — хибний обрив.

    «Закінчується на `</html>`» знімає обидва: позиція рядка перевіряється
    точно, а не вікном, і розмір хвоста більше ні на що не впливає.
    """
    if not rel.endswith(".dc.html"):
        return False
    return not data.rstrip().endswith(b"</html>")
