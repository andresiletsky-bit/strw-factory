#!/usr/bin/env python3
"""Сигнатура дизайн-одиниці — спільна для того, хто її ЗАПИСУЄ, і того, хто її
ЧИТАЄ.

Модуль існує рівно тому, що інакше регулярка жила б у двох файлах. `design-hash
.py` кладе сигнатуру в `index.yaml` як базову лінію, `design-emit.py` рахує
поточну і віднімає одну від одної. Розійдись ці два обчислення хоч на символ —
різниця перестала б означати «що змінилось» і почала б означати «чим ці два
файли не згодні». Тому обчислення одне, і воно тут.

Ім'я файла з підкресленням, а не з дефісом, — щоб його можна було
`import`увати: сусіди-скрипти лежать у тій самій теці, отже в `sys.path[0]`.
"""
import re

# Токеноподібні рядки: hex-кольори і `token.path` — саме те, що змінюється
# наскрізно й пояснює багато одиниць одразу.
TOKENISH = re.compile(r"#[0-9A-Fa-f]{6}\b|\b[a-z]+(?:\.[a-z-]+){1,3}\b")


def tokens_of(data):
    """Множина токеноподібних рядків одного файла (bytes → set[str])."""
    return set(TOKENISH.findall(data.decode("utf-8", "replace")))
