# want <rc> <правило або ""> <опис> <файл> [аргументи...]
want() {
  local rc="$1" rule="$2" desc="$3"; shift 3
  local out got
  out="$(python3 "${V}" "$@" 2>&1 < /dev/null)"; got=$?
  if [ "${got}" = "${rc}" ] && { [ -z "${rule}" ] || printf '%s\n' "${out}" | /usr/bin/grep -q -F -- "[${rule}]"; }; then
    printf 'ok   %s\n' "${desc}"; pass=$((pass + 1))
  else
    printf 'FAIL %s (rc=%s, чекали %s%s)\n%s\n' "${desc}" "${got}" "${rc}" "${rule:+, правило ${rule}}" "${out}" | sed '2,$s/^/     /'
    fail=$((fail + 1))
  fi
}

# Корінь «репо продукту» з джерелом підписів. Формат — справжній .xcstrings (JSON), ключ і
# значення uk; один рядок із форматом %@ — підпис із підстановкою.
mkrepo() { # mkrepo <тека>
  mkdir -p "$1/App/Resources" "$1/docs/smoke"
  cat > "$1/App/Resources/Localizable.xcstrings" <<'JSON'
{ "sourceLanguage": "uk", "version": "1.0", "strings": {
  "Створити перший простір": {},
  "join.code": { "localizations": { "uk": { "stringUnit": { "state": "translated", "value": "Приєднатись за кодом" } } } },
  "Видалити простір": {},
  "Скасувати": {},
  "delete.count": { "localizations": { "uk": { "variations": { "plural": {
      "one":   { "stringUnit": { "state": "translated", "value": "Видалити %lld договір" } },
      "other": { "stringUnit": { "state": "translated", "value": "Видалити %lld договорів" } } } } } } },
  "Вітаю, %@": {}
} }
JSON
}

