edit() { python3 - "$1" "$2" <<'PY'
import sys
p, expr = sys.argv[1], sys.argv[2]
s = open(p, encoding="utf-8").read()
new = eval(expr)
if new == s:
    sys.exit("мутація не наклалась: " + expr)   # не накладена мутація читається як пройдена проба
open(p, "w", encoding="utf-8").write(new)
PY
}

