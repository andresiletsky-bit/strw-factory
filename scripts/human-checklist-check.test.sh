#
# ЧОМУ ЦЕЙ НАБІР. Чотири запити human_smoke 04–06.09 казали лише «перевір X руками»; ніхто їх не
# пройшов, один мало не закрили як пройдений. Стандарт без валідатора — проза, а проза згниває.
# Тому кожне правило стандарту, яке можна поміряти, має тут ДВА випадки: зразок зелений, і копія
# зразка, зіпсована рівно в одному правилі, — червона з назвою саме цього правила. Без другого
# випадку набір доводив би лише «скрипт запускається».
#
# Свідок — назва правила у виводі, не лише код: rc 1 від чужої причини (зіпсований зразок) пройшов
# би перевірку коду, а правило, яке перевіряємо, могло б уже не працювати.
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
V="${HUMAN_CHECKLIST_CHECK:-${HERE}/human-checklist-check.py}"
T="$(mktemp -d)"; trap 'rm -rf "${T}"' EXIT
