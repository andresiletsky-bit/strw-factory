#!/usr/bin/env bash
# Чи вільно ЦЬОМУ контуру виконувати git-команди у змонтованій робочій копії.
#
# ЧОМУ ЦЕЙ СКРИПТ ІСНУЄ (tri-073, 2026-09-07). Хмарний headless-захід бачив
# робочу копію Mac як теку, де можна СТВОРЮВАТИ файли, але не СТИРАТИ. git
# кладе тимчасовий замок і одразу його прибирає; прибрати не зміг — і
# `.git/index.lock`, `.git/objects/maintenance.lock` лишились назавжди. Доки
# вони лежать, git у тому репо не працює ні в кого, і зняти їх може лише рука
# на Mac. Вимір заходу: `touch .writetest` — ок; `rm .writetest` → `Operation
# not permitted`; `git status --short` → `unable to unlink .git/index.lock`.
#
# Клас ширший за git: будь-який інструмент, що створює тимчасовий файл і
# розраховує його прибрати, у такому монтуванні лишає сміття назавжди.
#
# ПРЕДМЕТ ВИМІРУ — ІСНУВАННЯ ФАЙЛА ПІСЛЯ СПРОБИ, А НЕ КОД `rm`. Це не
# педантизм. Монтування tri-073 відмовляло ГУЧНО, і саме тому дефект помітили;
# тихий випадок — обгортка чи мережева ФС, яка приймає запит, повертає 0 і
# лишає файл, — гірший і цілком реальний. Скрипт, що вірить кодові виходу,
# назвав би такий контур здоровим і випустив би петлю брати git-локи.
#
# ТРИ СТАНИ, І СЕРЕДНІЙ НЕ ЗЛИВАЄТЬСЯ З КРАЙНІМИ:
#   0 — unlink працює  → git у змонтованих репо ДОЗВОЛЕНО;
#   1 — unlink не працює → git ЗАБОРОНЕНО, крім лише-читання з
#       `--no-optional-locks` (status --short, log, show, diff — саме те, що
#       contour-guard.sh пропускає в контурі C): без цього прапорця навіть
#       `git status` бере .git/index.lock; будь-який запис — теж лок;
#   2 — ПОМІРЯТИ НЕ ВДАЛОСЬ (теки немає, файл не створюється). Про unlink у
#       цьому разі не відомо НІЧОГО, і назвати це «дозволено» означало б
#       розказати відсутність як відповідь (`absence-told-as-answer`).
#
# Вивід — РІВНО один рядок у stdout (його читає Step 0 скіла `strw-loop-run`);
# подробиці йдуть у stderr.
#
# Переносність: bash 3.2 (macOS) і bash 5 (пісочниця) — жодної з форм, які
# перелічує `strw-state/scripts/lib/nonportable-forms.tsv`. Самі форми тут НЕ
# цитуються: цей файл — код, тобто предмет гейта, і літерал у коментарі
# збудив би перевірку на самого сторожа (у .tsv вони живуть законно, бо він
# дані, а не предмет — про це сказано в його ж шапці).
set -uo pipefail

dir="${1:-.}"

if [ ! -d "$dir" ]; then
    printf 'не поміряти: теки немає (%s) — про unlink нічого не відомо\n' "$dir"
    exit 2
fi

# ДЕ МІРЯТИ. Поверхня відмови tri-073 — `.git/` (там git кладе локи), тож у
# репо проба лягає саме туди: точніший предмет, і на зламаному монтуванні
# сміття лишається поза робочим деревом (не потрапить у `git add -A` наступної
# сесії). `.git` як ФАЙЛ (worktree) чи його відсутність — міряємо саму теку.
base="$dir"
[ -d "$dir/.git" ] && base="$dir/.git"

# $$ і $RANDOM у назві: два паралельні заходи не міряють той самий файл і не
# прибирають чужий; сам $$ — не гарантія (PID перевикористовуються).
probe="$base/.strw-mount-probe.$$.$RANDOM"

# `touch`, а не `: >`: перенаправлення оболонки не можна підмінити у PATH, а
# набір мусить уміти змоделювати «створити не вдалось» (випадок (e)).
touch "$probe" 2>/dev/null
if [ ! -e "$probe" ]; then
    printf 'не поміряти: у теці не створюється файл (%s) — про unlink нічого не відомо\n' "$base"
    exit 2
fi

# Код виходу свідомо ІГНОРУЄТЬСЯ: єдиний доказ — чи файл зник.
rm -f "$probe" 2>/dev/null

if [ -e "$probe" ]; then
    printf 'git ЗАБОРОНЕНО: монтування не видаляє файли — лишилось %s\n' "$probe"
    printf '   Наслідок: git-команда, що бере лок (навіть `git status` без прапорця),\n' >&2
    printf '   лишить незнищенний лок у .git/ і зламає репо для всіх, доки його не\n' >&2
    printf '   прибрати рукою. Дозволено лише читання з --no-optional-locks\n' >&2
    printf '   (status --short, log, show, diff); решта роботи — файлами і через\n' >&2
    printf '   _outbox/; самообмеження назвати у звіті (tri-073).\n' >&2
    exit 1
fi

printf 'git дозволено: монтування видаляє файли (%s)\n' "$dir"
exit 0
